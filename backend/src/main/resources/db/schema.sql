CREATE SCHEMA IF NOT EXISTS personas;
CREATE TABLE IF NOT EXISTS personas.profesion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(80) NOT NULL CHECK (length(trim(nombre)) > 0),
    nombre_clave VARCHAR(80) NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS personas.region (
    id VARCHAR(2) PRIMARY KEY CHECK (id ~ '^[0-9]{2}$'),
    nombre VARCHAR(100) NOT NULL CHECK (length(trim(nombre)) > 0)
);
CREATE TABLE IF NOT EXISTS personas.provincia (
    id VARCHAR(4) PRIMARY KEY CHECK (id ~ '^[0-9]{4}$'),
    nombre VARCHAR(100) NOT NULL CHECK (length(trim(nombre)) > 0),
    region_id VARCHAR(2) NOT NULL REFERENCES personas.region(id) ON DELETE RESTRICT,
    CONSTRAINT ck_provincia_region CHECK (left(id, 2) = region_id)
);
CREATE INDEX IF NOT EXISTS ix_provincia_region ON personas.provincia(region_id);
CREATE TABLE IF NOT EXISTS personas.distrito (
    id VARCHAR(6) PRIMARY KEY CHECK (id ~ '^[0-9]{6}$'),
    nombre VARCHAR(100) NOT NULL CHECK (length(trim(nombre)) > 0),
    provincia_id VARCHAR(4) NOT NULL REFERENCES personas.provincia(id) ON DELETE RESTRICT,
    CONSTRAINT ck_distrito_provincia CHECK (left(id, 4) = provincia_id)
);
CREATE INDEX IF NOT EXISTS ix_distrito_provincia ON personas.distrito(provincia_id);
CREATE TABLE IF NOT EXISTS personas.direccion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    detalle VARCHAR(200) NOT NULL CHECK (length(trim(detalle)) > 0),
    distrito_id VARCHAR(6) NOT NULL REFERENCES personas.distrito(id) ON DELETE RESTRICT
);
CREATE INDEX IF NOT EXISTS ix_direccion_distrito ON personas.direccion(distrito_id);
CREATE TABLE IF NOT EXISTS personas.persona (
    dni VARCHAR(8) PRIMARY KEY CHECK (dni ~ '^[0-9]{8}$'),
    nombres VARCHAR(100) NOT NULL CHECK (length(trim(nombres)) > 0),
    apellidos VARCHAR(100) NOT NULL CHECK (length(trim(apellidos)) > 0),
    direccion_id BIGINT NOT NULL,
    CONSTRAINT fk_persona_direccion FOREIGN KEY (direccion_id) REFERENCES personas.direccion(id) ON DELETE RESTRICT,
    CONSTRAINT uq_persona_direccion UNIQUE (direccion_id),
    profesion_id BIGINT NOT NULL REFERENCES personas.profesion(id) ON DELETE RESTRICT,
    celular VARCHAR(9) NOT NULL CHECK (celular ~ '^9[0-9]{8}$'),
    correo VARCHAR(180) NOT NULL CHECK (correo ~ '^[^[:space:]@]+@[^[:space:]@]+[.][^[:space:]@]+$'),
    foto_ruta VARCHAR(80) NOT NULL,
    CONSTRAINT ck_persona_foto_ruta CHECK (foto_ruta ~ '^([0-9]{8}/)?[0-9a-f-]{36}[.]jpg$'
        AND (foto_ruta NOT LIKE '%/%' OR split_part(foto_ruta, '/', 1) = dni)),
    estado BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE INDEX IF NOT EXISTS ix_persona_profesion ON personas.persona(profesion_id);
